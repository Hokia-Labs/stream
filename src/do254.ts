export const accomplishmentSummaryDocument = (
  requirements: ReadonlyArray<Requirement>,
  date: string,
): string => {
  const rev = twinRevision(requirements)
  const reports = problemReports(requirements)
  const summary = verificationSummary(requirements)
  const changes = twinChanges(requirements)
  const outstanding = summary.total - summary.complete
  const canClaim = reports.length === 0 && outstanding === 0
  return [
    ...header(
      'Hardware Accomplishment Summary',
      do254DocumentId('HAS', requirements),
      'DO-254 §10.9',
      requirements,
      date,
    ),
    '## 1. System & hardware overview',
    '',
    `(U) ${current(requirements, 'SYS-EPS')?.description ?? ''}`,
    '',
    '| Field | Value |',
    '| --- | --- |',
    `| Hardware item | ${partNumber(requirements)} Rev ${rev} (see ${do254DocumentId('HCI', requirements)}) |`,
    '| Hardware type | Circuit board assembly with one complex custom device (FPGA) |',
    '| Design assurance level | Level A (notional; set by the system safety assessment) |',
    '| Guidance | RTCA DO-254 / EUROCAE ED-80 with AC 20-152A objectives as tailored in PHAC-PSU-001 |',
    '| Airworthiness authority | Program military airworthiness authority (notional) |',
    '',
    '## 2. Stages of involvement',
    '',
    '| Review | Scope | Status |',
    '| --- | --- | --- |',
    `| SOI#1 | Planning: PHAC change supplement | ${rev === 'B' ? 'Planned' : 'Complete (Rev A)'} |`,
    `| SOI#2 | Design: requirements, design, implementation | ${rev === 'B' ? 'Not started' : 'Complete (Rev A)'} |`,
    `| SOI#3 | Validation & verification | ${rev === 'B' ? 'Not started' : 'Complete (Rev A)'} |`,
    `| SOI#4 | Final: conformity review, HAS, HCI | ${rev === 'B' ? 'Not started' : 'Complete (Rev A)'} |`,
    '',
    '## 3. Change summary',
    '',
    changes.length > 0
      ? `(U) Rev ${rev} changes ${changes.length} artifacts. See ${do254DocumentId('CIA', requirements)} for the impact analysis.`
      : '(U) Baseline issue, no changes.',
    '',
    ...changes.map(
      change =>
        `- ${change.artifact.id} (r${change.revision}): ${change.after}`,
    ),
    '',
    '## 4. Compliance status',
    '',
    `- Requirements verified: ${summary.complete} of ${summary.total}`,
    `- Requirements traced: ${summary.traced} of ${summary.total}`,
    `- Open problem reports: ${reports.length}`,
    '- Hardware conformity review: not yet performed',
    '',
    reports.length > 0 ? '| Problem report | Category | Title | Status |' : '',
    reports.length > 0 ? '| --- | --- | --- | --- |' : '',
    ...reports.map(
      item =>
        `| ${item.id} | ${item.category} | ${cell(item.title)} | ${item.status} |`,
    ),
    '',
    '## 5. Deviations from the PHAC',
    '',
    '(U) None identified.',
    '',
    '## 6. Compliance statement',
    '',
    canClaim
      ? '(U) The hardware item complies with PHAC-PSU-001 and the applicable DO-254 objectives.'
      : `(U) Compliance is not yet claimed. ${outstanding} requirements await re-verification and ${reports.length} problem reports are open. This summary will be reissued for SOI#4.`,
    '',
    '## 7. Sign-off',
    '',
    '| Role | Name | Signature | Date |',
    '| --- | --- | --- | --- |',
    '| Hardware lead | | | |',
    '| Verification lead | | | |',
    '| Process assurance | | | |',
    '| Certification liaison | | | |',
    '',
    ...footer,
  ].join('\n')
}

export const problemReportsCsv = (
  requirements: ReadonlyArray<Requirement>,
): string =>
  [
    ['ID', 'Category', 'Title', 'Source', 'Status', 'Corrective action'],
    ...problemReports(requirements).map(item => [
      item.id,
      item.category,
      item.title,
      item.source,
      item.status,
      item.action,
    ]),
  ]
    .map(row => row.map(csv).join(','))
    .join('\n')

export const do254Files = (
  requirements: ReadonlyArray<Requirement>,
  date: string,
): ReadonlyArray<PackageFile> => [
  {
    name: `${do254DocumentId('HAS', requirements)}.md`,
    content: accomplishmentSummaryDocument(requirements, date),
  },
  {
    name: `${do254DocumentId('HCI', requirements)}.md`,
    content: configurationIndexDocument(requirements, date),
  },
  {
    name: `${do254DocumentId('HVR', requirements)}.md`,
    content: verificationResultsDocument(requirements, date),
  },
  {
    name: `${do254DocumentId('CIA', requirements)}.md`,
    content: changeImpactDocument(requirements, date),
  },
  { name: 'problem-reports.csv', content: problemReportsCsv(requirements) },
]
